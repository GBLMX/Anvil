//! Built-in semantic palettes.

use super::*;

macro_rules! boxpigma_theme {
    (
        $name:literal,
        $bg:expr,
        $surface:expr,
        $text:expr,
        $accent:expr,
        $muted:expr,
        $border:expr,
        $error:expr,
        $warning:expr,
        $selection:expr
    ) => {
        Theme {
            name: $name,
            bg: $bg,
            surface: $surface,
            surface_alt: $surface,
            code_block_bg: $surface,
            border: $border,
            text: $text,
            muted: $muted,
            dim: $muted,
            accent: $accent,
            selection: $selection,
            success: $accent,
            warning: $warning,
            error: $error,
            magenta: $accent,
            white: Color::Rgb(255, 255, 255),
            syntax_keyword: $accent,
            syntax_string: $warning,
            syntax_comment: $muted,
            syntax_number: $warning,
            syntax_function: $text,
            syntax_type: $accent,
            syntax_property: $text,
            syntax_constant: $warning,
            syntax_heading: $accent,
            syntax_link: $text,
            syntax_code: $warning,
            syntax_emphasis: $accent,
            syntax_list: $warning,
            syntax_quote: $muted,
            syntax_table: $warning,
            syntax_modifiers: [Modifier::empty(); 15],
            status_modes: [None; 7],
        }
    };
}

